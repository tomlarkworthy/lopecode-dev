const ADV = 5.5;

// Render text -> array of polylines (in mm). anchor: 'start'|'middle'|'end'.
// size = cap height in mm. angle in degrees CCW about the anchor point.
export function textStrokes(str, { x = 0, y = 0, size = 6, anchor = "middle", angle = 0, spacing = 1 } = {}) {
  const chars = [...str.toUpperCase()];
  const scale = size / 6;
  const adv = ADV * scale * spacing;
  const width = chars.length * adv - (ADV * scale * (spacing - 1)) - 1.5 * scale;
  let ox = 0;
  if (anchor === "middle") ox = -width / 2;
  if (anchor === "end") ox = -width;
  const a = (angle * Math.PI) / 180, ca = Math.cos(a), sa = Math.sin(a);
  const out = [];
  chars.forEach((ch, i) => {
    const glyph = G[ch];
    if (!glyph) { if (ch !== " ") console.warn(`font: missing glyph '${ch}'`); return; }
    for (const stroke of glyph) {
      out.push(stroke.map(([gx, gy]) => {
        const lx = ox + i * adv + gx * scale;
        const ly = gy * scale;
        return [x + lx * ca - ly * sa, y + lx * sa + ly * ca];
      }));
    }
  });
  return out;
}

export function textWidth(str, size = 6, spacing = 1) {
  const scale = size / 6;
  return [...str].length * ADV * scale * spacing - (ADV * scale * (spacing - 1)) - 1.5 * scale;
}
