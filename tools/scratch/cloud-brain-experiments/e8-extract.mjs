// Cut the real compile + observableToJs cell functions out of the toolchain module (located with acorn).
import { parse } from "acorn"; import { readFileSync, writeFileSync } from "node:fs";
const src = readFileSync("toolchain.js", "utf8");
const ast = parse(src, { ecmaVersion: "latest", sourceType: "module" });
const want = { _mliwy8: "compileCell", _16p8atj: "observableToJsCell" };
let out = "// generated by e8-extract.mjs from @tomlarkworthy/observablejs-toolchain; do not edit\n";
for (const n of ast.body) if (n.type === "VariableDeclaration") for (const d of n.declarations) if (want[d.id.name]) out += `export const ${want[d.id.name]} = ${src.slice(d.init.start, d.init.end)};\n`;
writeFileSync("worker/toolchain-cells.js", out); console.log(out.length, (out.match(/export const/g) || []).length, /eval\(|new Function/.test(out));
