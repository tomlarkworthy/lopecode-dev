// ---------- derived source ----------

type Insertion = { pos: number; text: string };
type GenMap = { file: string; line: number; rule: string; prefix: string };

class Derived {
  text: string;
  genStartLine: number; // 0-based first generated line
  genStartPos: number;
  genMap = new Map<number, GenMap>(); // generated 0-based line -> origin
  constructor(public orig: string, public sfOrig: ts.SourceFile, public ins: Insertion[], gen: { text: string; map?: GenMap }[]) {
    ins.sort((a, b) => a.pos - b.pos);
    let out = "";
    let last = 0;
    for (const i of ins) {
      out += orig.slice(last, i.pos) + i.text;
      last = i.pos;
    }
    out += orig.slice(last);
    out += "\n// ---- generated by check.ts ----\n";
    this.genStartPos = out.length;
    this.genStartLine = out.split("\n").length - 1;
    gen.forEach((g, k) => {
      if (g.map) this.genMap.set(this.genStartLine + k, g.map);
    });
    out += gen.map((g) => g.text).join("\n") + "\n";
    this.text = out;
  }
  toOrigPos(dpos: number): number {
    let shift = 0;
    for (const i of this.ins) {
      const d = i.pos + shift;
      if (dpos >= d + i.text.length) shift += i.text.length;
      else if (dpos >= d) return i.pos;
      else break;
    }
    return dpos - shift;
  }
  loc(dpos: number) {
    const lc = this.sfOrig.getLineAndCharacterOfPosition(Math.min(this.toOrigPos(dpos), this.orig.length));
    return { line: lc.line + 1, col: lc.character + 1 };
  }
}

function hasOpenParen(fn: ts.FunctionLikeDeclaration, sf: ts.SourceFile) {
  return fn.getChildren(sf).some((c) => c.kind === ts.SyntaxKind.OpenParenToken);
}

function buildDerived(an: Analysis, file: "cells.ts" | "shell.ts"): Derived | null {
  const sf = file === "cells.ts" ? an.sfs.cells : an.sfs.shell;
  if (!sf) return null;
  const orig = sf.getFullText();
  const mine = an.cells.filter((c) => c.file === file);
  const foreignNames = new Set(an.foreign.map((f) => f.name));
  const other = file === "cells.ts" ? "./shell" : "./cells";
  const ins: Insertion[] = [];
  const gen: { text: string; map?: GenMap }[] = [];
  const usedForeign = new Set<string>();

  const valueAlias = (p: Param): string => {
    switch (p.source) {
      case "cell":
        return file === "cells.ts" ? `__V_${p.name}` : `import("./cells").__V_${p.name}`;
      case "shell":
        if (file === "shell.ts") return `__V_${p.name}`;
        if (foreignNames.has(p.name)) return (usedForeign.add(p.name), `__F_${p.name}`);
        return "Js";
      case "foreign":
        return (usedForeign.add(p.name), `__F_${p.name}`);
      case "capability":
        return CAPABILITIES[p.name];
      case "stdlib":
        return "any";
      default:
        return file === "cells.ts" ? "unknown" : "any";
    }
  };
  const refAlias = (p: Param): string =>
    (p.source === "cell") === (file === "cells.ts") ? `__R_${p.name}` : `import("${other}").__R_${p.name}`;

  for (const c of mine) {
    gen.push({ text: `export type __V_${c.name} = __CellValue<ReturnType<typeof ${c.name}>>; export type __R_${c.name} = __RefOf<ReturnType<typeof ${c.name}>>;`, map: { file, line: c.line, rule: "inject-type", prefix: `${c.name}: ` } });
    const needParens = ts.isArrowFunction(c.fn) && c.fn.parameters.length === 1 && !hasOpenParen(c.fn, sf);
    c.params.forEach((p, i) => {
      if (!p.plain) return;
      const pline = lineOf(sf, p.node.getStart(sf));
      if (!p.typed) {
        const at = (p.node.questionToken ?? p.node.name).end;
        if (needParens) ins.push({ pos: p.node.getStart(sf), text: "(" });
        ins.push({ pos: at, text: `: ${valueAlias(p)}${needParens ? ")" : ""}` });
        return;
      }
      if (p.source === "unknown" || p.source === "stdlib") return;
      if (p.refTyped && p.source !== "cell" && p.source !== "shell") return; // reported by analyze
      const src = p.refTyped ? refAlias(p) : valueAlias(p);
      gen.push({
        text: `{ const __chk: Parameters<typeof ${c.name}>[${i}] = (undefined as unknown as ${src}); }`,
        map: { file, line: pline, rule: p.refTyped ? "inject-state" : "inject-type", prefix: `${c.name}: parameter ${p.name} (${p.source} ${p.name})${p.refTyped ? " is typed State<…> so must name a cell returning StateCell<…>" : ""}: ` },
      });
    });
  }
  // Foreign values come from the module form of foreign.d.ts, so a name that is also a lib global
  // (location, name, ...) gets its declared type, not the lib one.
  for (const n of usedForeign) gen.push({ text: `type __F_${n} = typeof import("./__foreign").${n};` });
  if (file === "cells.ts") gen.push({ text: `export interface __Cells { ${mine.map((c) => `${c.name}: __V_${c.name};`).join(" ")} }` });
  else if (an.sfs.cells) gen.push({ text: `type ValueOf<K extends keyof import("./cells").__Cells> = import("./cells").__Cells[K];` });
  if (gen.length === 0) gen.push({ text: "export {};" });
  return new Derived(orig, sf, ins, gen);
}

// ---------- program ----------

const OPTIONS: ts.CompilerOptions = {
  strict: true,
  noEmit: true,
  target: ts.ScriptTarget.ES2023,
  module: ts.ModuleKind.ESNext,
  moduleResolution: ts.ModuleResolutionKind.Bundler,
  lib: ["lib.es2023.d.ts", "lib.dom.d.ts", "lib.dom.iterable.d.ts"],
  types: [],
  skipLibCheck: true,
  allowImportingTsExtensions: true,
};
const sfCache = new Map<string, ts.SourceFile>();

function makeProgram(overrides: Map<string, string>, roots: string[]) {
  const base = ts.createCompilerHost(OPTIONS, true);
  const host: ts.CompilerHost = {
    ...base,
    getSourceFile(fileName, lang, onError) {
      const o = overrides.get(fileName);
      if (o != null) return ts.createSourceFile(fileName, o, lang, true);
      const cacheable = fileName.includes("/node_modules/typescript/lib/") || fileName === PRELUDE_PATH;
      if (cacheable && sfCache.has(fileName)) return sfCache.get(fileName);
      const sf = base.getSourceFile(fileName, lang, onError);
      if (cacheable && sf) sfCache.set(fileName, sf);
      return sf;
    },
    fileExists: (f) => overrides.has(f) || base.fileExists(f),
    readFile: (f) => overrides.get(f) ?? base.readFile(f),
  };
  return ts.createProgram({ rootNames: roots, options: OPTIONS, host });
}

// ---------- lint helpers ----------

const isFnLike = (n: ts.Node): n is ts.FunctionLikeDeclaration =>
  ts.isArrowFunction(n) || ts.isFunctionExpression(n) || ts.isFunctionDeclaration(n) || ts.isMethodDeclaration(n) ||
  ts.isGetAccessorDeclaration(n) || ts.isSetAccessorDeclaration(n) || ts.isConstructorDeclaration(n);

function enclosingFn(n: ts.Node): ts.Node | undefined {
  for (let a = n.parent; a; a = a.parent) if (isFnLike(a)) return a;
  return undefined;
}

function climb(n: ts.Node): ts.Node {
  for (;;) {
    const p = n.parent;
    if (!p) return n;
    if (ts.isParenthesizedExpression(p) || ts.isAsExpression(p) || ts.isSatisfiesExpression(p) || ts.isNonNullExpression(p) || ts.isTypeAssertionExpression(p)) { n = p; continue; }
    if (ts.isConditionalExpression(p) && p.condition !== n) { n = p; continue; }
    if (ts.isBinaryExpression(p)) {
      const k = p.operatorToken.kind;
      if (k === ts.SyntaxKind.BarBarToken || k === ts.SyntaxKind.AmpersandAmpersandToken || k === ts.SyntaxKind.QuestionQuestionToken) { n = p; continue; }
      if (k === ts.SyntaxKind.CommaToken && p.right === n) { n = p; continue; }
    }
    return n;
  }
}

type Sink = "read" | "arg" | "return" | "yield" | "alias" | "assign" | "literal";
function classify(n: ts.Node): { sink: Sink; at: ts.Node } {
  const p = n.parent;
  if (ts.isCallExpression(p) || ts.isNewExpression(p)) {
    if (p.arguments?.some((a) => a === n)) return { sink: "arg", at: p };
    return { sink: "read", at: p };
  }
  if (ts.isReturnStatement(p)) return { sink: "return", at: p };
  if (ts.isArrowFunction(p) && p.body === n) return { sink: "return", at: p };
  if (ts.isYieldExpression(p)) return { sink: "yield", at: p };
  if (ts.isVariableDeclaration(p) && p.initializer === n) return { sink: "alias", at: p };
  if (ts.isBinaryExpression(p) && p.right === n && p.operatorToken.kind >= ts.SyntaxKind.FirstAssignment && p.operatorToken.kind <= ts.SyntaxKind.LastAssignment)
    return { sink: "assign", at: p };
  if (ts.isArrayLiteralExpression(p) || (ts.isPropertyAssignment(p) && p.initializer === n) || ts.isShorthandPropertyAssignment(p))
    return { sink: "literal", at: p };
  return { sink: "read", at: p };
}

function isValueRef(id: ts.Identifier): boolean {
  const p = id.parent;
  for (let a: ts.Node | undefined = id; a && !ts.isSourceFile(a); a = a.parent) {
    if (ts.isExpressionWithTypeArguments(a)) continue;
    if (ts.isTypeNode(a) || ts.isTypeAliasDeclaration(a) || ts.isInterfaceDeclaration(a) || ts.isTypeParameterDeclaration(a)) return false;
  }
  if ((ts.isPropertyAccessExpression(p) || ts.isQualifiedName(p)) && p.name === id) return false;
  if ((ts.isPropertyAssignment(p) || ts.isMethodDeclaration(p) || ts.isPropertyDeclaration(p) || ts.isGetAccessorDeclaration(p) ||
       ts.isSetAccessorDeclaration(p) || ts.isPropertySignature(p) || ts.isEnumMember(p) || ts.isEnumDeclaration(p) || ts.isModuleDeclaration(p)) && p.name === id) return false;
  if ((ts.isVariableDeclaration(p) || ts.isParameter(p) || ts.isFunctionDeclaration(p) || ts.isFunctionExpression(p) ||
       ts.isClassDeclaration(p) || ts.isClassExpression(p)) && p.name === id) return false;
  if (ts.isBindingElement(p) && (p.name === id || p.propertyName === id)) return false;
  if (ts.isLabeledStatement(p) || ts.isBreakStatement(p) || ts.isContinueStatement(p) || ts.isMetaProperty(p)) return false;
  if (ts.isImportSpecifier(p) || ts.isImportClause(p) || ts.isNamespaceImport(p) || ts.isExportSpecifier(p)) return false;
  return true;
}

function forEachDescendant(n: ts.Node, f: (n: ts.Node) => void) {
  const visit = (c: ts.Node) => { f(c); ts.forEachChild(c, visit); };
  ts.forEachChild(n, visit);
}

function rootOf(e: ts.Expression): ts.Expression {
  for (;;) {
    if (ts.isPropertyAccessExpression(e) || ts.isElementAccessExpression(e) || ts.isParenthesizedExpression(e) || ts.isNonNullExpression(e)) e = e.expression;
    else return e;
  }
}

// ---------- lint ----------

function lintCells(program: ts.Program, d: Derived, sf: ts.SourceFile, cells: Cell[], push: (n: ts.Node | number, rule: string, msg: string) => void) {
  const checker = program.getTypeChecker();
  const inOrig = (n: ts.Node) => n.pos < d.genStartPos;
  const brand = (t: ts.Type, key: string) => !!checker.getPropertyOfType(checker.getApparentType(t), key);
  const typeOf = (n: ts.Node) => checker.getTypeAtLocation(n);
  const isMut = (n: ts.Node) => brand(typeOf(n), "__lc_mut");
  const isBorrowed = (n: ts.Node) => brand(typeOf(n), "__lc_borrowed");
  const isRef = (n: ts.Node) => brand(typeOf(n), "__lc_state");
  const isAction = (n: ts.Node) => brand(typeOf(n), "__lc_action");
  const symDecl = (s: ts.Symbol | undefined) => s?.declarations?.[0];
  const fromPrelude = (id: ts.Node) => symDecl(checker.getSymbolAtLocation(id))?.getSourceFile().fileName === PRELUDE_PATH;
  const fromLib = (id: ts.Node) => {
    const dd = symDecl(checker.getSymbolAtLocation(id));
    return !!dd && program.isSourceFileDefaultLibrary(dd.getSourceFile());
  };
  const isPreludeCall = (n: ts.Node, name: string): n is ts.CallExpression =>
    ts.isCallExpression(n) && ts.isIdentifier(n.expression) && n.expression.text === name && fromPrelude(n.expression);
  const cellNames = new Set(cells.map((c) => c.name));
  const isPrimitive = (t: ts.Type): boolean => {
    if (t.isUnion()) return t.types.every(isPrimitive);
    const P = ts.TypeFlags.StringLike | ts.TypeFlags.NumberLike | ts.TypeFlags.BigIntLike | ts.TypeFlags.BooleanLike | ts.TypeFlags.ESSymbolLike |
      ts.TypeFlags.Undefined | ts.TypeFlags.Null | ts.TypeFlags.Void | ts.TypeFlags.Never | ts.TypeFlags.EnumLike;
    return (t.flags & P) !== 0;
  };
  const isCollection = (t: ts.Type): boolean => {
    if (t.isUnion() || t.isIntersection()) return t.types.some(isCollection);
    const c = checker as unknown as { isArrayType?: (t: ts.Type) => boolean; isTupleType?: (t: ts.Type) => boolean };
    if (c.isArrayType?.(t) || c.isTupleType?.(t)) return true;
    const s = t.getSymbol() ?? t.aliasSymbol;
    return !!s && COLLECTIONS.has(s.getName());
  };
  const mutReceiver = (recv: ts.Expression) => isMut(recv) || isMut(rootOf(recv));
  const helperMemo = new Map<ts.Node, boolean>();

  // --- syntactic + type rules over the whole original region ---
  const text = sf.getFullText();
  const ignoreRe = /@ts-(ignore|expect-error|nocheck)\b/g;
  for (let m; (m = ignoreRe.exec(text)) && m.index < d.genStartPos; ) push(m.index, "no-ts-ignore", `@ts-${m[1]} is banned`);

  forEachDescendant(sf, (n) => {
    if (!inOrig(n)) return;
    const top = n.parent && ts.isSourceFile(n.parent); // top-level ones are reported by analyze
    const k = n.kind;
    if (k === ts.SyntaxKind.AnyKeyword) push(n, "no-any", "any is banned");
    else if (ts.isAsExpression(n) || ts.isTypeAssertionExpression(n)) {
      const t = n.type;
      if (!(ts.isTypeReferenceNode(t) && ts.isIdentifier(t.typeName) && t.typeName.text === "const")) push(n, "no-cast", "cast is banned (only as const)");
    } else if (ts.isNonNullExpression(n)) push(n, "no-non-null", "non-null assertion is banned");
    else if (ts.isDeleteExpression(n)) push(n, "no-delete", "delete is banned");
    else if (k === ts.SyntaxKind.ThisKeyword) push(n, "no-this", "this is banned");
    else if ((ts.isClassDeclaration(n) && !top) || ts.isClassExpression(n)) push(n, "no-class", "class is banned");
    else if (ts.isEnumDeclaration(n) && !top) push(n, "no-enum", "enum is banned");
    else if (ts.isModuleDeclaration(n) && !top) push(n, "no-namespace", "namespace is banned");
    else if (ts.isVariableDeclarationList(n) && !(n.flags & (ts.NodeFlags.Let | ts.NodeFlags.Const)) && !(n.parent && ts.isVariableStatement(n.parent) && ts.isSourceFile(n.parent.parent)))
      push(n, "no-var", "var is banned");
    else if (ts.isCallExpression(n) && n.expression.kind === ts.SyntaxKind.ImportKeyword) push(n, "no-dynamic-import", "import() is banned");
    else if (ts.isNewExpression(n)) {
      const e = n.expression;
      if (ts.isIdentifier(e) && fromLib(e)) { /* intrinsic, or a non-intrinsic global reported by free-name */ }
      else push(n, "new-non-intrinsic", `new ${e.getText(sf)}: only allowed intrinsics may be constructed`);
    } else if (ts.isBinaryExpression(n)) {
      const op = n.operatorToken.kind;
      if (op >= ts.SyntaxKind.FirstAssignment && op <= ts.SyntaxKind.LastAssignment) {
        for (const l of assignTargets(n.left)) {
          if ((ts.isPropertyAccessExpression(l) || ts.isElementAccessExpression(l)) && !mutReceiver(l.expression))
            push(n, "member-write", `write to ${l.getText(sf)}: receiver is not Mut`);
          letCapture(l, n);
        }
      } else if (op === ts.SyntaxKind.EqualsEqualsEqualsToken || op === ts.SyntaxKind.ExclamationEqualsEqualsToken ||
                 op === ts.SyntaxKind.EqualsEqualsToken || op === ts.SyntaxKind.ExclamationEqualsToken) {
        if (!isPrimitive(typeOf(n.left)) && !isPrimitive(typeOf(n.right))) push(n, "strict-eq-object", "=== on two non-primitive operands; use equals(a, b)");
      }
    } else if ((ts.isPrefixUnaryExpression(n) || ts.isPostfixUnaryExpression(n)) &&
               (n.operator === ts.SyntaxKind.PlusPlusToken || n.operator === ts.SyntaxKind.MinusMinusToken)) {
      const o = n.operand;
      if ((ts.isPropertyAccessExpression(o) || ts.isElementAccessExpression(o)) && !mutReceiver(o.expression))
        push(n, "member-write", `${o.getText(sf)}++/--: receiver is not Mut`);
      letCapture(o, n);
    } else if (ts.isCallExpression(n) && ts.isPropertyAccessExpression(n.expression)) {
      const pa = n.expression;
      const name = pa.name.text;
      if (MUTATING.has(name) && isCollection(typeOf(pa.expression)) && !mutReceiver(pa.expression))
        push(n, "mutating-method", `${pa.getText(sf)}(): mutating method on a non-Mut value`);
      if (name === "assign" && ts.isIdentifier(pa.expression) && pa.expression.text === "Object" && fromLib(pa.expression)) {
        const first = n.arguments[0];
        let f0: ts.Expression | undefined = first;
        while (f0 && ts.isParenthesizedExpression(f0)) f0 = f0.expression;
        if (f0 && !ts.isObjectLiteralExpression(f0) && !isMut(f0)) push(n, "object-assign", "Object.assign onto an existing value");
      }
    } else if ((ts.isPropertyAccessExpression(n) || ts.isElementAccessExpression(n)) &&
               (ts.isPropertyAccessExpression(n) ? n.name.text : ts.isStringLiteral(n.argumentExpression) ? n.argumentExpression.text : "") === "random" &&
               typeOf(n.expression).getSymbol()?.getName() === "Math") {
      push(n, "banned-member", "Math.random is banned; take the random capability");
    }
  });

  // Targets of an assignment, including destructuring patterns ([o.a] = …, ({ k: o.b } = …)).
  function assignTargets(l: ts.Expression): ts.Expression[] {
    while (ts.isParenthesizedExpression(l)) l = l.expression;
    if (ts.isArrayLiteralExpression(l)) return l.elements.flatMap((e) => assignTargets(ts.isSpreadElement(e) ? e.expression : e));
    if (ts.isObjectLiteralExpression(l))
      return l.properties.flatMap((p) =>
        ts.isPropertyAssignment(p) ? assignTargets(p.initializer) : ts.isShorthandPropertyAssignment(p) ? [p.name] : ts.isSpreadAssignment(p) ? assignTargets(p.expression) : []);
    if (ts.isBinaryExpression(l) && l.operatorToken.kind === ts.SyntaxKind.EqualsToken) return assignTargets(l.left); // default value
    return [l];
  }

  function letCapture(target: ts.Expression, at: ts.Node) {
    if (!ts.isIdentifier(target)) return;
    let decl: ts.Node | undefined = symDecl(checker.getSymbolAtLocation(target));
    while (decl && (ts.isBindingElement(decl) || ts.isObjectBindingPattern(decl) || ts.isArrayBindingPattern(decl))) decl = decl.parent;
    if (!decl || !ts.isVariableDeclaration(decl) || !(decl.parent.flags & ts.NodeFlags.Let)) return;
    const df = enclosingFn(decl);
    if (!df) return;
    // v1: allowed when every function between the assignment and the let is a non-escaping local helper.
    for (let g = enclosingFn(at); g && g !== df; g = enclosingFn(g))
      if (!isLocalHelper(g)) return push(at, "let-capture", `let ${target.text} assigned from a nested function that escapes (or is not a named local helper)`);
  }

  // A helper bound to a local const or function declaration whose every use is a direct call.
  function isLocalHelper(g: ts.Node): boolean {
    if (helperMemo.has(g)) return helperMemo.get(g)!;
    let nameNode: ts.Identifier | undefined;
    if (ts.isFunctionDeclaration(g) && g.name) nameNode = g.name;
    else if (ts.isArrowFunction(g) || ts.isFunctionExpression(g)) {
      let u: ts.Node = g;
      while (ts.isParenthesizedExpression(u.parent)) u = u.parent;
      const vd = u.parent;
      if (ts.isVariableDeclaration(vd) && vd.initializer === u && ts.isIdentifier(vd.name) && vd.parent.flags & ts.NodeFlags.Const) nameNode = vd.name;
    }
    const sym = nameNode && checker.getSymbolAtLocation(nameNode);
    let ok = !!sym;
    if (sym)
      forEachDescendant(sf, (n) => {
        if (!ok || !ts.isIdentifier(n) || n === nameNode || !isValueRef(n)) return;
        const s2 = ts.isShorthandPropertyAssignment(n.parent) ? checker.getShorthandAssignmentValueSymbol(n.parent) : checker.getSymbolAtLocation(n);
        if (s2 === sym && !(ts.isCallExpression(n.parent) && n.parent.expression === n)) ok = false;
      });
    helperMemo.set(g, ok);
    return ok;
  }

  // a type that mentions State or StateCell anywhere: properties, elements, union members, type arguments, signatures
  const holdsRef = (t: ts.Type, seen = new Set<ts.Type>(), depth = 0): string | null => {
    if (seen.has(t) || depth > 10) return null;
    seen.add(t);
    if (isPrimitive(t)) return null;
    if (t.isUnionOrIntersection()) { for (const x of t.types) { const w = holdsRef(x, seen, depth + 1); if (w) return w; } return null; }
    if (brand(t, "__lc_state")) return "State";
    if (brand(t, "__lc_statecell")) return "StateCell";
    const parts: ts.Type[] = [];
    const args = [...((t as ts.TypeReference).target ? checker.getTypeArguments(t as ts.TypeReference) : []), ...(t.aliasTypeArguments ?? [])];
    const decl = symDecl(t.getSymbol());
    // a library type (Array, Map, Promise, ...) is judged by its type arguments, not its members
    if (decl && program.isSourceFileDefaultLibrary(decl.getSourceFile())) parts.push(...args);
    else {
      parts.push(...args);
      for (const p of checker.getPropertiesOfType(t)) parts.push(checker.getTypeOfSymbol(p));
      for (const sig of [...t.getCallSignatures(), ...t.getConstructSignatures()]) {
        parts.push(sig.getReturnType(), ...sig.getParameters().map((p) => checker.getTypeOfSymbol(p)));
      }
      const ix = t.getNumberIndexType() ?? t.getStringIndexType();
      if (ix) parts.push(ix);
    }
    for (const x of parts) { const w = holdsRef(x, seen, depth + 1); if (w) return w; }
    return null;
  };

  // action-capture: state-dependent cells, with the reason. A state cell, a generator, a cell taking a
  // capability other than invalidation or log, or a shell value, and a cell taking one of these by value.
  const stateful = new Map<string, string>();
  // cell.params come from the first analysis; the program's own parameter node is fn.parameters[i]
  const progParam = (c: Cell, p: Param) => c.fn.parameters[c.params.indexOf(p)];
  const takesByValue = (c: Cell, p: Param) => {
    if (p.refTyped) return false;
    const pn = progParam(c, p);
    const t = pn?.type;
    if (t && ts.isTypeReferenceNode(t) && ts.isIdentifier(t.typeName) && (t.typeName.text === "Events" || t.typeName.text === "State")) return false;
    return !(pn && isAction(pn.name));
  };
  for (let changed = true; changed; ) {
    changed = false;
    for (const c of cells) {
      if (stateful.has(c.name)) continue;
      let why: string | null = c.returnsRef ? "is a state cell" : c.isGenerator ? "is a generator" : null;
      for (const p of c.params) {
        if (why) break;
        if (p.facet === "capability" && p.name !== "invalidation" && p.name !== "log") why = `takes the capability ${p.name}`;
        else if (p.source === "shell" && takesByValue(c, p)) why = `reads the shell cell ${p.name}`;
        else if (p.source === "cell" && takesByValue(c, p) && stateful.has(p.name)) why = `reads ${p.name}`;
      }
      if (why) { stateful.set(c.name, why); changed = true; }
    }
  }

  // --- per-cell symbol and brand rules ---
  for (const cell of cells) {
    const fn = cell.fn;
    {
      // action-capture: a use, inside an action body, of a state-dependent parameter or of a local of
      // the cell computed from one
      const taint = new Map<ts.Node, string>();
      for (const p of cell.params) {
        const pn = progParam(cell, p);
        if (!pn) continue;
        if (p.facet === "capability" && p.name !== "invalidation" && p.name !== "log") taint.set(pn, `capability ${p.name}`);
        else if (p.source === "shell" && takesByValue(cell, p)) taint.set(pn, "a shell cell's value");
        else if (p.source === "cell" && takesByValue(cell, p) && stateful.has(p.name)) taint.set(pn, stateful.get(p.name) === "is a state cell" ? `the value of the state cell ${p.name}` : stateful.get(p.name) === "is a generator" ? `the latest value of the events cell ${p.name}` : `${p.name} ${stateful.get(p.name)}`);
      }
      const actionFnOf = (n: ts.Node): ts.Node | undefined => {
        for (let a = n.parent; a && a !== fn; a = a.parent)
          if (isFnLike(a) && a.parent && isPreludeCall(a.parent, "action") && a.parent.arguments.some((x) => x === a)) return a;
        return undefined;
      };
      const declOf = (id: ts.Identifier) => (ts.isShorthandPropertyAssignment(id.parent) ? checker.getShorthandAssignmentValueSymbol(id.parent) : checker.getSymbolAtLocation(id))?.declarations?.[0];
      if (taint.size) {
        const locals: { decl: ts.Node; from: ts.Node }[] = [];
        forEachDescendant(fn, (n) => {
          if (actionFnOf(n)) return;
          if (ts.isVariableDeclaration(n) && n.initializer) locals.push({ decl: n, from: n.initializer });
          if (ts.isFunctionDeclaration(n) && n.body) locals.push({ decl: n, from: n.body });
        });
        for (let changed = true; changed; ) {
          changed = false;
          for (const l of locals) {
            if (taint.has(l.decl)) continue;
            let hit: string | null = null;
            forEachDescendant(l.from, (n) => { if (!hit && ts.isIdentifier(n) && isValueRef(n)) { const d = declOf(n); if (d && taint.has(d)) hit = `computed from ${n.text}`; } });
            if (hit) { taint.set(l.decl, hit); changed = true; }
          }
        }
        const seen = new Set<string>();
        forEachDescendant(fn, (n) => {
          if (!ts.isIdentifier(n) || !isValueRef(n)) return;
          const af = actionFnOf(n);
          if (!af) return;
          const d = declOf(n);
          if (!d || !taint.has(d) || (d.pos >= af.pos && d.end <= af.end)) return;
          const key = `${n.text}@${actionFnOf(n)!.pos}`;
          if (seen.has(key)) return;
          seen.add(key);
          const why = taint.get(d)!;
          push(n, "action-capture", why.startsWith("capability ")
            ? `${n.text} is a capability, so an action using it would make the stored state depend on something the calls do not record; take the value as an argument of the action`
            : `${n.text} depends on state (${why}), so an action using it would act on the value from the cell's last run; read the state cell inside the action with read(...), or pass the value to the action when it is called`);
        });
      }
    }
    {
      const sig = checker.getSignaturesOfType(typeOf(fn), ts.SignatureKind.Call)[0];
      const ret = sig?.getReturnType();
      if (ret && !cell.isGenerator && ret.getSymbol()?.getName() === "StateCell" && brand(ret, "__lc_statecell")) {
        const inner = checker.getTypeOfSymbol(checker.getPropertyOfType(ret, "__lc_statecell")!);
        const w = holdsRef(inner, new Set());
        if (w) push(fn, "state-in-state", `a state cell holds ${checker.typeToString(inner)}, which contains ${w}; a state cell's content may not contain a State or StateCell`);
      }
    }
    // The cell's own function is not a local: a self-reference is a reference by module-level name.
    const isLocal = (decl: ts.Declaration) => decl !== fn && decl.getSourceFile() === sf && decl.pos >= fn.pos && decl.end <= fn.end;
    const insideAction = (n: ts.Node) => {
      for (let a = n.parent; a && a !== fn; a = a.parent)
        if (isFnLike(a) && a.parent && isPreludeCall(a.parent, "action") && a.parent.arguments.some((x) => x === a)) return true;
      return false;
    };
    const awaitsIn = new Map<ts.Node, number[]>();
    const mutRefs = new Map<ts.Symbol, ts.Identifier[]>();
    const freezeEnd = new Map<ts.Symbol, number>();

    forEachDescendant(fn, (n) => {
      if (ts.isAwaitExpression(n) || (ts.isForOfStatement(n) && n.awaitModifier)) {
        const f = enclosingFn(n)!;
        (awaitsIn.get(f) ?? awaitsIn.set(f, []).get(f)!).push(n.end);
      }
    });

    forEachDescendant(fn, (n) => {
      // prelude constructor placement
      if (isPreludeCall(n, "mut")) {
        const c = climb(n);
        const p = c.parent;
        if (!(ts.isVariableDeclaration(p) && p.initializer === c && p.parent.flags & ts.NodeFlags.Const))
          push(n, "mut-bind", "mut(...) must initialise a local const");
      } else if (isPreludeCall(n, "borrow")) {
        const c = climb(n);
        if (!(ts.isYieldExpression(c.parent) && enclosingFn(n) === fn && cell.isGenerator))
          push(n, "borrow-placement", "borrow(x) only as `yield borrow(x)` in a generator cell");
      } else if (isPreludeCall(n, "state")) {
        const c = climb(n);
        // Same shape run.ts recognises (analyze.returnsRefCall): concise body, or a return directly in the cell body.
        let u: ts.Node = n;
        while (ts.isParenthesizedExpression(u.parent) || ts.isSatisfiesExpression(u.parent)) u = u.parent;
        const body = fn.body;
        const ok = !cell.isGenerator && !cell.isAsync &&
          (body === u || (!!body && ts.isBlock(body) && ts.isReturnStatement(u.parent) && u.parent.parent === body));
        if (!ok) push(n, "state-placement", "state(...) only as the concise body or a top-level return of a sync cell");
      }
      if (ts.isCallExpression(n)) {
        const e = n.expression;
        if (ts.isPropertyAccessExpression(e) && (e.name.text === "set" || e.name.text === "update") && isRef(e.expression) && !insideAction(n))
          push(n, "state-write", `${e.getText(sf)}(): State writes only inside action(...)`);
        else if (!isPreludeCall(n, "action") && isAction(e) && !insideAction(n))
          push(n, "action-call", `${e.getText(sf)}(): an Action may be called only inside action(...)`);
        else if (isPreludeCall(n, "read") && !insideAction(n))
          push(n, "read-outside-action", "read(...) is only for an action body; a cell takes the value as a parameter");
      }

      if (!ts.isIdentifier(n) || !isValueRef(n)) return;
      const sym = ts.isShorthandPropertyAssignment(n.parent) ? checker.getShorthandAssignmentValueSymbol(n.parent) : checker.getSymbolAtLocation(n);
      const name = n.text;
      if (name === "arguments") return push(n, "no-arguments", "arguments is banned");
      const decls = sym?.declarations ?? [];
      const local = decls.some(isLocal);
      if (!local) {
        if (!sym) return; // unresolved: TypeScript reports it
        if (decls.length === 0) { if (!INTRINSICS.has(name)) push(n, "free-name", `free name ${name}`); return; }
        const dsf = decls[0].getSourceFile();
        if (dsf.fileName === PRELUDE_PATH) { if (!PRELUDE_VALUES.has(name)) push(n, "free-name", `free name ${name}`); return; }
        if (program.isSourceFileDefaultLibrary(dsf)) { if (!INTRINSICS.has(name)) push(n, "free-name", `free name ${name} (not an allowed intrinsic)`); return; }
        if (dsf === sf && cellNames.has(name)) return push(n, "cell-by-name", `cell ${name} referenced by its module-level name; take it as a parameter`);
        return push(n, "free-name", `free name ${name}`);
      }
      const decl = decls[0];
      const declFn = ts.isParameter(decl) ? decl.parent : enclosingFn(decl);
      const captured = enclosingFn(n) !== declFn;
      const c = climb(n);
      const { sink, at } = classify(c);

      if (isMut(n)) {
        (mutRefs.get(sym!) ?? mutRefs.set(sym!, []).get(sym!)!).push(n);
        if (captured) push(n, "mut-capture", `Mut ${name} captured by a nested function`);
        else if (sink === "arg") {
          if (isPreludeCall(at, "freeze")) freezeEnd.set(sym!, Math.min(freezeEnd.get(sym!) ?? Infinity, at.end));
          else if (!brand(checker.getContextualType(c as ts.Expression) ?? checker.getAnyType(), "__lc_mut"))
            push(n, "mut-escape", `Mut ${name} passed to a parameter not typed Mut`);
        } else if (sink !== "read") push(n, "mut-escape", `Mut ${name} ${sink === "alias" || sink === "assign" ? "aliased" : sink === "literal" ? "placed in a literal" : sink + "ed"}`);
      }
      if (isBorrowed(n)) {
        if (captured) push(n, "borrowed-escape", `Borrowed ${name} captured by a nested function`);
        else if (sink === "return" || sink === "yield" || sink === "literal" || sink === "assign") push(n, "borrowed-escape", `Borrowed ${name} escapes (${sink})`);
        else if (sink === "alias" && !(ts.isVariableDeclaration(at) && at.parent.flags & ts.NodeFlags.Const)) push(n, "borrowed-escape", `Borrowed ${name} held in a let`);
        else if (sink === "arg") {
          const callee = (at as ts.CallExpression).expression;
          if (isPreludeCall(at, "state") || (ts.isPropertyAccessExpression(callee) && (callee.name.text === "set" || callee.name.text === "update") && isRef(callee.expression)))
            push(n, "borrowed-escape", `Borrowed ${name} put in a state cell`);
        }
        const ef = enclosingFn(n)!;
        if ((awaitsIn.get(ef) ?? []).some((end) => end <= n.getStart(sf))) push(n, "borrowed-await", `Borrowed ${name} used after an await`);
      }
      if (isAction(n) && sink === "arg" && !isPreludeCall(at, "action")) {
        const ctx = checker.getContextualType(c as ts.Expression);
        if (!ctx || !brand(ctx, "__lc_action")) push(n, "action-pass", `Action ${name} passed to a parameter not typed Action`);
      }
    });

    for (const [sym, refs] of mutRefs) {
      const fe = freezeEnd.get(sym);
      if (fe == null) continue;
      for (const r of refs) if (r.getStart(sf) >= fe) push(r, "mut-after-freeze", `Mut ${sym.getName()} used after freeze`);
    }
  }
}

// ---------- tiers ----------

function tierOf(cell: Cell, checker: ts.TypeChecker, prelude: (n: ts.Node, name: string) => boolean): CellReport["tier"] {
  if (cell.file === "shell.ts") return "shell";
  if (cell.returnsRef) return "state";
  const sig = checker.getSignatureFromDeclaration(cell.fn);
  if (sig && checker.getPropertyOfType(checker.getReturnTypeOfSignature(sig), "__lc_statecell")) return "state";
  let borrow = false, mutUse = false;
  forEachDescendant(cell.fn, (n) => {
    if (prelude(n, "borrow")) borrow = true;
    if (prelude(n, "mut")) mutUse = true;
  });
  if (cell.isGenerator && borrow) return "owner";
  if (mutUse) return "mut-local";
  return "default";
}

// ---------- main ----------

export function checkPort(dir: string): CheckResult {
  const an = analyze(dir);
  const errors: CheckError[] = an.errors.map((e: SyntaxError_) => ({ ...e, col: 1 }));
  const dc = buildDerived(an, "cells.ts");
  const ds = buildDerived(an, "shell.ts");
  const P = (f: string) => join(an.files.dir, f);
  const overrides = new Map<string, string>();
  const roots = [PRELUDE_PATH];
  if (an.files.foreign != null && an.sfs.foreign) {
    // Module form (values; read by __F_ aliases) and a global form holding only type declarations.
    const ft = an.files.foreign;
    const names = an.sfs.foreign.statements.flatMap((st) =>
      ts.isVariableStatement(st) ? st.declarationList.declarations.flatMap((d) => (ts.isIdentifier(d.name) ? [d.name.text] : []))
      : (ts.isFunctionDeclaration(st) || ts.isClassDeclaration(st) || ts.isModuleDeclaration(st) || ts.isTypeAliasDeclaration(st) || ts.isInterfaceDeclaration(st)) && st.name && ts.isIdentifier(st.name) ? [st.name.text] : []);
    overrides.set(P("__foreign.ts"), ft + `\nexport { ${[...new Set(names)].join(", ")} };\n`);
    let types = ft.replace(/[^\n]/g, " ");
    for (const st of an.sfs.foreign.statements)
      if (ts.isTypeAliasDeclaration(st) || ts.isInterfaceDeclaration(st))
        types = types.slice(0, st.getFullStart()) + ft.slice(st.getFullStart(), st.end) + types.slice(st.end);
    overrides.set(P("__foreign_types.d.ts"), types);
    roots.push(P("__foreign.ts"), P("__foreign_types.d.ts"));
  }
  if (dc) { overrides.set(P("cells.ts"), dc.text); roots.push(P("cells.ts")); }
  if (ds) { overrides.set(P("shell.ts"), ds.text); roots.push(P("shell.ts")); }
  const program = makeProgram(overrides, roots);
  const derivedOf = (f: string) => (f === P("cells.ts") ? dc : f === P("shell.ts") ? ds : null);

  for (const diag of ts.getPreEmitDiagnostics(program)) {
    const msg = ts.flattenDiagnosticMessageText(diag.messageText, "\n");
    if (!diag.file) { errors.push({ file: "-", line: 0, col: 0, rule: `ts${diag.code}`, message: msg }); continue; }
    const fn = diag.file.fileName;
    const d = derivedOf(fn);
    if (d) {
      const dl = diag.file.getLineAndCharacterOfPosition(diag.start ?? 0).line;
      if (dl >= d.genStartLine) {
        const g = d.genMap.get(dl);
        errors.push(g ? { file: g.file, line: g.line, col: 1, rule: g.rule, message: g.prefix + msg } : { file: fn.endsWith("shell.ts") ? "shell.ts" : "cells.ts", line: 0, col: 0, rule: `ts${diag.code}`, message: "(generated) " + msg });
        continue;
      }
      const { line, col } = d.loc(diag.start ?? 0);
      errors.push({ file: fn.endsWith("shell.ts") ? "shell.ts" : "cells.ts", line, col, rule: `ts${diag.code}`, message: msg });
    } else if (fn === P("__foreign.ts") || fn === PRELUDE_PATH) {
      const lc = diag.file.getLineAndCharacterOfPosition(diag.start ?? 0);
      errors.push({ file: fn === PRELUDE_PATH ? "prelude.d.ts" : "foreign.d.ts", line: lc.line + 1, col: lc.character + 1, rule: `ts${diag.code}`, message: msg });
    }
  }

  const checker = program.getTypeChecker();
  const fromPrelude = (n: ts.Node, name: string) =>
    ts.isCallExpression(n) && ts.isIdentifier(n.expression) && n.expression.text === name &&
    checker.getSymbolAtLocation(n.expression)?.declarations?.[0]?.getSourceFile().fileName === PRELUDE_PATH;

  // Cells re-extracted from the derived source files so nodes belong to the program.
  const derivedCells: Cell[] = [];
  for (const [d, file] of [[dc, "cells.ts"], [ds, "shell.ts"]] as const) {
    if (!d) continue;
    const sf = program.getSourceFile(P(file))!;
    const cs = extractCells(sf, file, []);
    const orig = an.cells.filter((c) => c.file === file);
    cs.forEach((c, i) => { c.params = orig[i]?.params ?? c.params; c.line = orig[i]?.line ?? c.line; });
    derivedCells.push(...cs);
    if (file === "cells.ts")
      lintCells(program, d, sf, cs, (n, rule, message) => {
        const pos = typeof n === "number" ? n : n.getStart(sf);
        const { line, col } = d.loc(pos);
        errors.push({ file: "cells.ts", line, col, rule, message });
      });
  }

  // Attribute errors to cells by line range.
  const ranges = derivedCells.map((c) => {
    const d = c.file === "cells.ts" ? dc! : ds!;
    const sf = program.getSourceFile(P(c.file))!;
    return { c, from: d.loc(c.statement.getStart(sf)).line, to: d.loc(c.statement.end).line };
  });
  for (const e of errors) e.cell = ranges.find((r) => r.c.file === e.file && e.line >= r.from && e.line <= r.to)?.c.name;
  errors.sort((a, b) => (a.file + String(a.line).padStart(6, "0")).localeCompare(b.file + String(b.line).padStart(6, "0")));

  const cells: CellReport[] = derivedCells.map((c) => ({
    name: c.name,
    file: c.file,
    kind: c.kind,
    tier: tierOf(c, checker, fromPrelude),
    inputs: c.params.map((p) => ({ name: p.name, facet: p.facet, source: p.source })),
    errors: errors.filter((e) => e.cell === c.name && e.file === c.file),
  }));
  return { port: an.files.dir, ok: errors.length === 0, errors, cells, foreign: an.foreign };
}

if (import.meta.main) {
  const args = process.argv.slice(2);
  const dir = args.find((a) => !a.startsWith("--"));
  if (!dir) { console.error("usage: bun check.ts ports/<name> [--json]"); process.exit(2); }
  const r = checkPort(resolve(dir));
  if (args.includes("--json")) console.log(JSON.stringify(r, null, 2));
  else {
    for (const e of r.errors) console.log(`${dir}/${e.file}:${e.line}:${e.col} [${e.rule}] ${e.message}`);
    const tiers: Record<string, number> = {};
    for (const c of r.cells) tiers[c.tier] = (tiers[c.tier] ?? 0) + 1;
    console.log(`${r.cells.length} cells (${Object.entries(tiers).map(([k, v]) => `${k} ${v}`).join(", ")}), ${r.errors.length} error(s)`);
  }
  process.exit(r.ok ? 0 : 1);
}
