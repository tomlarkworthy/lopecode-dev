// Generates the NESTED node types from the flat prototype's spec (../flat-ast/out/spec-a.json: 121 node types + Other,
// derived by its census.ts/gen.ts), with child fields typed as nodes instead of indices, and the children function the
// walks need in place of `for (const k in n)`.
//   ast-n.ss.ts    one record per node type; every node has nid (pre-order number, stamped by adapter.ts), start, end,
//                  line. A child field is AstNode, AstNode | null, AstNode[] or (AstNode | null)[]. Any other node type
//                  is an Other node: its acorn type in kind, its child fields in fields, its other fields in props.
//   kids-n.ss.ts   childrenOf(n): the node's children with the key holding each, in acorn's key order (merged over
//                  the corpus, out/keyorder.json; keyorder.ts shows the relative order of child keys never conflicts)
// Names: AstNode (Node is a DOM type), nid (acorn already has an `id` field: a function's or declarator's name).
// AstNode lists members most frequent first (the flat record: cross() tries a union's members in order).
// Run: bun gen.ts [--all]   (--all: the 133 census types, ../flat-ast/out/spec-a-all.json, into ast-n-all.ss.ts)
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const HERE = import.meta.dir, FLAT = join(HERE, "../flat-ast/out");
type Field = { key: string; how: "node" | "list" | "value"; ts: string };
const all = process.argv.includes("--all");
const spec: Record<string, Field[]> = JSON.parse(readFileSync(join(FLAT, all ? "spec-a-all.json" : "spec-a.json"), "utf8"));
const census: Record<string, { count: number }> = JSON.parse(readFileSync(join(FLAT, "census.json"), "utf8"));
const orders: Record<string, Record<string, number>> = JSON.parse(readFileSync(join(HERE, "out/keyorder.json"), "utf8"));

// the child keys of t in an order consistent with every key order seen (a topological merge); throws on a conflict
export function childOrder(t: string, fields: Field[]): string[] {
  const kids = fields.filter((f) => f.how !== "value").map((f) => f.key);
  const before = new Map(kids.map((k) => [k, new Set<string>()]));
  for (const seq of Object.keys(orders[t] ?? {})) {
    const ks = seq.split(",").filter((k) => before.has(k));
    for (let i = 0; i < ks.length; i++) for (let j = i + 1; j < ks.length; j++) before.get(ks[j]!)!.add(ks[i]!);
  }
  const out: string[] = [];
  const left = new Set(kids);
  while (left.size) {
    const next = [...left].find((k) => [...before.get(k)!].every((b) => !left.has(b)));
    if (!next) throw new Error(`${t}: child key orders conflict`);
    out.push(next); left.delete(next);
  }
  for (const k of out) for (const b of before.get(k)!) if (out.indexOf(b) > out.indexOf(k)) throw new Error(`${t}: ${b} before ${k} not kept`);
  return out;
}
const tsOf = (f: Field) => f.how === "node" ? f.ts.replace("number", "AstNode") : f.how === "list" ? (f.ts.includes("null") ? "(AstNode | null)[]" : "AstNode[]") : f.ts;

const types = Object.keys(spec);
const byFreq = types.toSorted((a, b) => (census[b]?.count ?? 0) - (census[a]?.count ?? 0));
const lines = [`// GENERATED by selfhost/nested-ast/gen.ts from ../flat-ast/out/${all ? "spec-a-all" : "spec-a"}.json; do not edit. ${types.length} node types + Other.
// A parse as a nested tree: each child field holds the child node. nid is the node's number in a pre-order walk
// (adapter.ts), unique within one parse; line is loc.start.line.
`];
for (const t of types) lines.push(`export type ${t} = { ${[`type: "${t}"`, "nid: number", "start: number", "end: number", "line: number", ...spec[t]!.map((f) => `${f.key}: ${tsOf(f)}`)].join("; ")} };`);
lines.push(`export type OtherField = { key: string; list: boolean; nodes: (AstNode | null)[] };
export type OtherProp = { key: string; value: string | number | boolean | null };
// a node type the checker does not name: its acorn type in kind, its child fields and its other fields as lists
export type Other = { type: "Other"; nid: number; start: number; end: number; line: number; kind: string; fields: OtherField[]; props: OtherProp[] };`);
lines.push(`export type AstNode =\n  | ${[...byFreq, "Other"].join("\n  | ")};`);
lines.push(`export type Comment = { block: boolean; text: string; start: number; end: number; line: number };
export type NestedAst = { program: AstNode; comments: Comment[]; src: string; lineStarts: number[]; count: number };
// a parse: the tree, or acorn's error as a value
export type NParse = { ok: true; ast: NestedAst } | { ok: false; message: string; pos: number; line: number; column: number };
`);
writeFileSync(join(HERE, all ? "ast-n-all.ss.ts" : "ast-n.ss.ts"), lines.join("\n"));

// childrenOf
const K = [`// GENERATED by selfhost/nested-ast/gen.ts; do not edit. childrenOf(n): the children of n, each with the key of the
// field holding it, in acorn's key order (the order \`for (const k in n)\` walks). A null child or hole is left out.
export type Kid = { key: string; node: AstNode };
export const childrenOf = () => (n: AstNode): Kid[] => {
  const one = (key: string, x: AstNode | null): Kid[] => (x === null ? [] : [{ key, node: x }]);
  const many = (key: string, xs: (AstNode | null)[]): Kid[] => xs.flatMap((x) => one(key, x));
  switch (n.type) {`];
const order: Record<string, string[]> = {};
for (const t of types) {
  const ks = childOrder(t, spec[t]!);
  order[t] = ks;
  if (!ks.length) continue;
  const f = new Map(spec[t]!.map((x) => [x.key, x]));
  const parts = ks.map((k) => f.get(k)!.how === "list" ? `...many("${k}", n.${k})` : f.get(k)!.ts.includes("null") ? `...one("${k}", n.${k})` : `{ key: "${k}", node: n.${k} }`);
  K.push(`    case "${t}": return [${parts.join(", ")}];`);
}
K.push(`    case "Other": return n.fields.flatMap((f) => many(f.key, f.nodes));`);
K.push(`    default: return [];`, `  }`, `};`, ``);
writeFileSync(join(HERE, all ? "kids-n-all.ss.ts" : "kids-n.ss.ts"), K.join("\n"));
writeFileSync(join(HERE, `out/childorder${all ? "-all" : ""}.json`), JSON.stringify(order));
console.log(`${all ? "ast-n-all" : "ast-n"}.ss.ts: ${types.length} records + Other; kids: ${Object.values(order).filter((x) => x.length).length} cases with children`);
