// The differential's programs: one arrow function each, parameters annotated (the real checker converts them), a
// block body of constructs in the slice only (slice.ts asserts it). `err` lists the rules the real checker is expected
// to report, as a check on the program set itself, not on the shapes.
export type Program = { name: string; src: string; err?: string[] };
const P = (name: string, params: string, body: string, err?: string[]): Program => ({ name, src: `const p = (${params}) => {\n${body}\n};`, err });
