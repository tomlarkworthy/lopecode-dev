// Generates the flat-table node types (layout A: one record per node type, children as indices) from the census
// (census.ts) and the named set (kinds.ts). Two unions:
//   ast-a.ss.ts      the node types the checker names (kinds.ts) that acorn produces, plus Program and TemplateElement
//                    (reached through fields the checker reads), every other type as one Other row
//   ast-a-all.ss.ts  every node type in the census as its own record, plus Other (a stress test of the union size)
// Every row has start, end, line (loc.start.line), parent (-1 at the root), field (the parent's key holding it) and
// after (one past the last row of its subtree; rows are in pre-order).
// A field census saw absent or undefined on some node is null there. loc and extra are dropped; a Literal's value is
// null for a regex or a bigint (regex and bigint, which acorn also gives, are kept).
// Run: bun selfhost/flat-ast/gen.ts   (writes ast-a.ss.ts, ast-a-all.ss.ts, out/spec-a.json, out/spec-a-all.json)
import { writeFileSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { census, type Census } from "./census.ts";

const HERE = import.meta.dir;
export const DROPPED = ["loc", "extra"];
const COMMON = ["type", "start", "end"];

// a field's TS type and how the adapter fills it: node, list (of nodes, maybe null holes), or value
export type FieldSpec = { key: string; how: "node" | "list" | "value"; ts: string };
export function specOf(c: Census, kinds: string[]): Record<string, FieldSpec[]> {
  const out: Record<string, FieldSpec[]> = {};
  for (const t of kinds) {
    const fs: FieldSpec[] = [];
    for (const [key, ks] of Object.entries(c[t]!.fields)) {
      if (COMMON.includes(key) || DROPPED.includes(key)) continue;
      const nullable = ks.some((k) => k === "null" || k === "undefined" || k === "absent");
      const core = ks.filter((k) => k !== "null" && k !== "undefined" && k !== "absent");
      const orNull = (s: string) => (nullable ? `${s} | null` : s);
      if (core.length === 1 && core[0] === "node") fs.push({ key, how: "node", ts: orNull("number") });
      else if (core.every((k) => k === "node[]" || k === "node?[]") && core.length) fs.push({ key, how: "list", ts: core.includes("node?[]") ? "(number | null)[]" : "number[]" });
      else if (core.length === 0) fs.push({ key, how: "value", ts: "null" });
      else {
        const prims = core.map((k) => (k === "regexp" || k === "bigint" ? "null" : k === "record" ? recordTs(t, key) : k));
        if (prims.some((p) => p === "node" || p === "node[]" || p === "other[]")) throw new Error(`${t}.${key}: mixed ${core.join(" ")}`);
        const u = [...new Set([...prims, ...(nullable ? ["null"] : [])])];
        fs.push({ key, how: "value", ts: u.join(" | ") });
      }
    }
    out[t] = fs;
  }
  return out;
}
// the two record-valued fields acorn gives (after extra is dropped)
const recordTs = (t: string, key: string) => {
  if (t === "Literal" && key === "regex") return "{ pattern: string; flags: string }";
  if (t === "TemplateElement" && key === "value") return "{ raw: string; cooked: string | null }";
  throw new Error(`no record type for ${t}.${key}`);
};

const HEADER = (what: string) => `// GENERATED by selfhost/flat-ast/gen.ts from the census of the corpus; do not edit. ${what}
// A parse as a flat table: nodes[0] is the Program, each child field holds the index of a node in nodes.
// parent is -1 at the root; field is the key of the parent field holding the node. Rows are in pre-order, so the
// subtree of node i is the rows i .. after-1.
`;
const TAIL = `export type OtherField = { key: string; list: boolean; nodes: (number | null)[] };
export type OtherProp = { key: string; value: string | number | boolean | null };
// a node type the checker does not name: its type in kind, its child fields and its other fields as lists
export type Other = { type: "Other"; start: number; end: number; line: number; parent: number; field: string; after: number; kind: string; fields: OtherField[]; props: OtherProp[] };
export type Comment = { block: boolean; text: string; start: number; end: number; line: number };
export type FlatAst = { nodes: FNode[]; comments: Comment[]; src: string; lineStarts: number[] };
// a parse: the table, or acorn's error as a value
export type Parse = { ok: true; ast: FlatAst } | { ok: false; message: string; pos: number; line: number; column: number };
`;

// FNode lists its members most frequent first: cross() tries a union's members in order (probe-cross-order.ts)
export function emit(spec: Record<string, FieldSpec[]>, what: string, count: (t: string) => number = () => 0): string {
  const lines = [HEADER(what)];
  for (const [t, fs] of Object.entries(spec)) {
    const body = [`type: "${t}"`, "start: number", "end: number", "line: number", "parent: number", "field: string", "after: number", ...fs.map((f) => `${f.key}: ${f.ts}`)];
    lines.push(`export type ${t} = { ${body.join("; ")} };`);
  }
  lines.push(`export type FNode =\n  | ${[...Object.keys(spec).toSorted((a, b) => count(b) - count(a)), "Other"].join("\n  | ")};`);
  lines.push(TAIL);
  return lines.join("\n");
}

if (import.meta.main) {
  const c = census();
  const K = JSON.parse(readFileSync(join(HERE, "out/kinds.json"), "utf8"));
  // named by lite/*.ts or by the survey's file set (which adds the toolchain files)
  const named = [...Object.keys(K.named), ...K.surveyFilesNamed];
  const checkerKinds = [...new Set([...named.filter((t) => c[t]), "Program", "TemplateElement"])].sort();
  const allKinds = Object.keys(c).sort();
  for (const [file, kinds, what] of [["ast-a", checkerKinds, `The ${checkerKinds.length} node types: those lite/*.ts or the survey files name (kinds.ts) that acorn produces, plus Program and TemplateElement.`], ["ast-a-all", allKinds, `All ${allKinds.length} node types of the census.`]] as const) {
    const spec = specOf(c, [...kinds]);
    writeFileSync(join(HERE, `${file}.ss.ts`), emit(spec, what, (t) => c[t]?.count ?? 0));
    writeFileSync(join(HERE, `out/spec-${file.slice(4)}.json`), JSON.stringify(spec));
    console.log(`${file}.ss.ts: ${kinds.length} node records + Other, ${Object.values(spec).reduce((s, f) => s + f.length, 0)} fields`);
  }
}
