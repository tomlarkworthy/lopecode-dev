// Runtime behaviour of immer 11 for the hazards the probes ask about. Run: bun selfhost/sched-immer/demo/hazards.ts
import { Immer, enableMapSet, current, isDraft } from "immer";
enableMapSet();
const im = new Immer({ autoFreeze: true });
const base = { n: 0, inner: { a: 1 }, m: new Map([[1, { a: 1 }]]), buf: new Float32Array(2), d: new Date(0) };
const out: string[] = [];
const t = (name: string, f: () => unknown) => { try { out.push(`${name}: ${String(f())}`); } catch (e) { out.push(`${name}: throws ${(e as Error).message.slice(0, 90)}`); } };
let leak: any;
im.produce(base, (d) => { leak = d.inner; });
t("sub-object read after produce", () => leak.a);
let leakM: any;
im.produce(base, (d) => { leakM = d.m.get(1); });
t("Map value read after produce", () => leakM.a);
t("mutate and return", () => im.produce(base, (d: any) => { d.n = 1; return { n: 2 }; }));
t("async recipe result is a Promise", () => im.produce(base, async (d: any) => { d.n = 1; }) instanceof Promise);
t("generator recipe: n after", () => (im.produce(base, function* (d: any) { d.n = 1; } as any) as any).n);
const r1 = im.produce(base, (d) => { d.buf[0] = 7; });
t("typed array write reaches base", () => base.buf[0]);
t("typed array shared with result", () => r1.buf === base.buf);
im.produce(base, (d) => { d.d.setTime(5); });
t("Date write reaches base", () => base.d.getTime());
const user = { x: 1 };
const r2 = im.produce(base, (d: any) => { d.user = user; });
t("inserted user object frozen", () => Object.isFrozen(user));
t("draft === base inside recipe", () => { let s = false; im.produce(base, (d) => { s = (d as any) === base; }); return s; });
t("draft.inner === base.inner inside recipe", () => { let s = false; im.produce(base, (d) => { s = d.inner === base.inner; }); return s; });
t("nested produce on a draft", () => im.produce(base, (d) => { im.produce(d, (e) => { e.n = 3; }); }).n);
t("current() copy is a draft", () => { let c: any; im.produce(base, (d) => { c = current(d.inner); }); return isDraft(c) + " " + c.a; });
const mb = { n: 0 };
const r3 = im.produce(mb, (d) => { d.n = 1; });
mb.n = 9;
t("base mutated after produce: result.n", () => r3.n);
console.log(out.join("\n"));
