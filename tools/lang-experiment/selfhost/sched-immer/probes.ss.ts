// Probes: produce modelled as a helper taking a recipe (d: Mut<S>) => void. One case per cell.
type I = { readonly a: number; readonly tags: readonly string[] };
type S = { readonly n: number; readonly xs: readonly number[]; readonly inner: I; readonly m: Map<number, I>; readonly buf: Float32Array };
let base = (): S => ({ n: 0, xs: [1], inner: { a: 1, tags: [] }, m: new Map(), buf: new Float32Array(2) });
let produce = () => (b: S, recipe: (d: Mut<S>) => void): S => { const d = mut({ ...b }); recipe(d); return freeze(d); };
let keepIt = () => (s: S) => s.n;
let ok_control = (produce, base) => produce(base, (d) => { d.n = d.n + 1; d.xs = [...d.xs, 2]; });
let ok_control_block_fn = (produce, base) => { const r = produce(base, (d) => { d.n = 5; }); return r.n; };
let p01_return_draft = (produce, base) => produce(base, (d) => d);
let p02_return_draft_block = (produce, base) => produce(base, (d) => { return d; });
