import { chromium } from "../../../node_modules/playwright/index.mjs";
import { offlineWithAir } from "../lite/soundscript/theme-check.ts";
const file = new URL("../../../lopebooks/notebooks/soundscript.html", import.meta.url).pathname;
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
await offlineWithAir(page, []);
page.on("console", (m) => { if (m.text().startsWith("PROBE")) console.log(m.text()); });
await page.goto(`file://${file}#view=R100(S100(@tomlarkworthy/soundscript-spec))`);
await page.waitForFunction(() => (window as any).__ojs_runtime?.mains?.get("@tomlarkworthy/soundscript-spec")?._scope.get("spec_editor")?._value, null, { timeout: 90000 });
const out = await page.evaluate(async () => {
  const rt = (window as any).__ojs_runtime, m = rt.mains.get("@tomlarkworthy/soundscript-spec");
  const v = (n: string) => m._scope.get(n)._value;
  const spec_editor = v("spec_editor"), spec_stream = v("spec_stream");
  const B = await spec_editor(spec_stream(1000000));
  const proto = Object.getPrototypeOf(B.variable("seen") ?? m._scope.get("spec_editor"));
  const log: string[] = [];
  const orig = proto.define;
  proto.define = function (...a: any[]) { log.push(`define ${typeof a[0] === "string" ? a[0] : this._name}`); return orig.apply(this, a); };
  const fr = () => new Promise((r) => requestAnimationFrame(r));
  for (let i = 0; i < 30; i++) await fr();
  const s0 = await B.value("seen");
  log.push("--- edit onNum");
  await B.edit("onNum", "const onNum = (nums: Events<number>, record: Action<[number]>) => /* again */ on(nums, record);");
  for (let i = 0; i < 30; i++) await fr();
  const s1 = await B.value("seen");
  proto.define = orig;
  const names = [...rt._variables].filter((x: any) => x._module === B.variable("seen")?._module).map((x: any) => `${x._name} <- ${x._inputs.map((i: any) => i._name)}`);
  B.dispose();
  return { s0, s1, log, names };
});
console.log(JSON.stringify(out, null, 1));
await browser.close();
