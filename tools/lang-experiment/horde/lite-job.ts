// bun horde/lite-job.ts : builds the Job that SoundScript's compile would send for batchOnPool, the same
// way lite/stdlib/runtime.ts compiler() does (check, island, erase), and bundles lite/browser/workers.ts
// (pagePool, unchanged) as a classic script. Both are read from lite/ and written under horde/proto/.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { checkSources } from "../lite/core.ts";
import { island } from "../lite/island.ts";
import { erase } from "../lite/browser/erase.ts";
const source = readFileSync(join(import.meta.dir, "cells.ts"), "utf8");
const result = checkSources({ cells: source, tsx: false }, { strictIndex: false });
const byName = new Map([...result.facts!.values()].map((info) => [info.name, { info, text: source.slice(info.span![0], info.span![1]) }] as const));
const spec = { inputs: ["batch", "base", "frame", "flow", "crowd", "binned", "bullets", "player"], refs: ["maze", "params"], outputs: ["nextAgents", "hits"] };
const isl = island([...byName.values()].map(({ info }) => ({ name: info.name, params: info.params.map((p) => p.name), refCell: info.returnsRef })), spec);
if (isl.problems.length) throw new Error(JSON.stringify(isl.problems));
const verdict = new Map(result.cells.map((c) => [c.name, c.status]));
const notOk = ["batchOnPool", ...isl.order].filter((n) => verdict.get(n) !== "ok");
if (notOk.length) throw new Error("not ok: " + notOk);
const js = erase(isl.order.map((n) => byName.get(n)!.text).join("\n\n"));
const order = isl.order.map((n) => ({ name: n, params: byName.get(n)!.info.params.map((p) => p.name) }));
const job = { key: "island1:batchOnPool", js, names: isl.order, order, outputs: spec.outputs };
writeFileSync(join(import.meta.dir, "proto/lite-job.js"), `// GENERATED by horde/lite-job.ts\nvar LITE_JOB = ${JSON.stringify(job)};\n`);
console.log("island order:", isl.order.join(", "), "| js", js.length, "chars");
const b = await Bun.build({ entrypoints: [join(import.meta.dir, "lite-pool-entry.ts")], format: "iife", minify: false });
writeFileSync(join(import.meta.dir, "proto/lite-pool.js"), "// GENERATED by horde/lite-job.ts from lite/browser/workers.ts\n" + (await b.outputs[0].text()));
console.log("proto/lite-pool.js written");
