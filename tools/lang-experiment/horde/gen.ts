// bun horde/gen.ts : erases cells.ts (lite's own erase, read-only) into proto/sim.gen.js, a classic
// script defining hordeSim(), which wires the cells by hand in dependency order. Workers are built
// from hordeSim.toString(), so main thread and workers run the same text.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { erase } from "../lite/browser/erase.ts";
const src = readFileSync(join(import.meta.dir, "cells.ts"), "utf8");
// the compile call is a capability use; it is not part of the plain-JS simulation
const js = erase(src).replace(/const batchOnPool = [\s\S]*?\n  \}\);\n/, "");
const out = `// GENERATED by horde/gen.ts from horde/cells.ts. Do not edit.
function hordeSim() {
"use strict";
const mut = (x) => x, freeze = (x) => x;
${js}
const P = params(), X = xs32(), H = hash01(X), M = maze(P, X);
const sim = { params: P, maze: M, hash01: H, flowOf: flowOf(), gridOf: gridOf(), binsOf: binsOf(), stepBatch: stepBatch(H), initial: initial(M, P, H) };
sim.test = () => test_batches_do_not_matter(M, P, sim.initial, sim.flowOf, sim.gridOf, sim.binsOf, sim.stepBatch);
return sim;
}
`;
writeFileSync(join(import.meta.dir, "proto/sim.gen.js"), out);
console.log(`proto/sim.gen.js ${out.length} bytes`);
