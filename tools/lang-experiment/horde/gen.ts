// bun horde/gen.ts : erases cells.ts (lite's own erase, read-only) into proto/sim.gen.js, a classic
// script defining hordeSim(), which evaluates the cells in dependency order (the order lite's checker
// reports their parameters in) and returns every cell's value. Workers are built from
// hordeSim.toString(), so main thread and workers run the same text. Refuses to write unless the
// default (strict) checker accepts every cell.
//
// It also writes proto/sim-raw.gen.js, the same code with every checked read atF(a, i), atI(a, i), atMF(a, i), ...
// turned back into a[i]: the A/B arm for what strict indexing costs. The game never loads it.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { erase } from "../lite/browser/erase.ts";
import { checkSources } from "../lite/core.ts";
import { parse, kids, type Node } from "../lite/parse.ts";
const src = readFileSync(join(import.meta.dir, "cells.ts"), "utf8");
const result = checkSources({ cells: src, tsx: false });
const bad = result.cells.filter((c) => c.status !== "ok");
if (bad.length) { console.error("strict check fails:", bad.map((c) => c.name).join(", ")); process.exit(1); }
const facts = [...result.facts!.values()];
const CAPS = new Set(["compile", "pool", "now", "random", "fetch", "log", "invalidation"]);
const names = new Set(facts.map((f) => f.name));
const order: string[] = [];
const seen = new Set<string>();
const byName = new Map(facts.map((f) => [f.name, f]));
const visit = (n: string) => {
  if (seen.has(n)) return;
  seen.add(n);
  const f = byName.get(n)!;
  for (const p of f.params) if (names.has(p.name)) visit(p.name);
  order.push(n);
};
for (const f of facts) visit(f.name);
const runnable = order.filter((n) => !n.startsWith("test_") && !byName.get(n)!.params.some((p) => CAPS.has(p.name) || !names.has(p.name)));
const call = (n: string) => `${n}(${byName.get(n)!.params.map((p) => "v." + p.name).join(", ")})`;
const js = erase(src);
const body = (code: string) => `"use strict";
const mut = (x) => x, freeze = (x) => x;
${code}
const v = {};
${runnable.map((n) => `v.${n} = ${call(n)};`).join("\n")}
v.test = () => ${call("test_batches_do_not_matter")};
return v;`;
// atF(a, i) etc. -> (a)[i] for the raw arm
const P = parse(js);
const edits: [number, number, string][] = [];
const walk = (n: Node) => {
  if (n.type === "CallExpression" && n.callee.type === "Identifier" && /^at(M\w*|F|I|U8)?$/.test(n.callee.name) && n.arguments.length === 2) {
    edits.push([n.start, n.end, ""]);
  }
  kids(n).forEach(walk);
};
walk(P.program);
const rawOf = (from: number, to: number): string => {
  let out = "", pos = from;
  for (const [s, e] of edits) {
    if (s < pos || e > to) continue;
    const n = findCall(s, e);
    out += js.slice(pos, s) + `(${rawOf(n.arguments[0].start, n.arguments[0].end)})[${rawOf(n.arguments[1].start, n.arguments[1].end)}]`;
    pos = e;
  }
  return out + js.slice(pos, to);
};
const calls = new Map<string, Node>();
const index = (n: Node) => { if (n.type === "CallExpression") calls.set(`${n.start}:${n.end}`, n); kids(n).forEach(index); };
index(P.program);
const findCall = (s: number, e: number) => calls.get(`${s}:${e}`)!;
edits.sort((a, b) => a[0] - b[0]);
// keep the helper cells themselves (the raw arm simply never calls them)
const raw = rawOf(0, js.length);
const header = (what: string) => `// GENERATED by horde/gen.ts from horde/cells.ts (${what}). Do not edit.\n`;
writeFileSync(join(import.meta.dir, "proto/sim.gen.js"), header("strict: every read through a checked helper") + `function hordeSim() {\n${body(js)}\n}\n`);
writeFileSync(join(import.meta.dir, "proto/sim-raw.gen.js"), header("raw: at(a, i) rewritten to a[i], for the cost comparison only") + `function hordeSim() {\n${body(raw)}\n}\n`);
console.log(`proto/sim.gen.js and proto/sim-raw.gen.js: ${runnable.length} cells evaluated in order, ${edits.length} checked reads (${(raw.match(/\bat(M\w*|F|I|U8)?\(/g) || []).length} helper calls left in raw, the helper definitions)`);
