// span invariants

const isSpan = (v) => Array.isArray(v) && v.length === 2 && typeof v[0] === 'number' && typeof v[1] === 'number';

/** Every span is in range and well ordered. */
function checkSpans(parsed, src, trail) {
  const seen = new Set();
  const walk = (v, path) => {
    if (v === null || v === undefined) return;
    if (seen.has(v)) return;
    if (isSpan(v)) {
      assert.ok(v[0] >= 0, `${path}[0] >= 0 ${trail}`);
      assert.ok(v[1] <= src.length, `${path}[1] <= len ${trail}`);
      assert.ok(v[1] >= v[0], `${path} ordered ${trail}`);
      return;
    }
    if (v instanceof Map) { for (const [k, val] of v) walk(val, `${path}.${k}`); return; }
    if (Array.isArray(v)) { seen.add(v); v.forEach((x, i) => walk(x, `${path}[${i}]`)); return; }
    if (typeof v !== 'object') return;
    seen.add(v);
    for (const k of Object.keys(v)) walk(v[k], `${path}.${k}`);
  };
  walk({ h: parsed.header, n: parsed.nodes, e: parsed.edges, s: parsed.styles, g: parsed.subgraphs, t: parsed.statements, x: parsed.errors }, '');
}

/** Every recorded text field equals the slice of its own span. */
function checkRoundTrip(parsed, src, trail) {
  const eq = (span, text, what) => assert.equal(src.slice(span[0], span[1]), text, `${what} ${trail}`);
  for (const n of parsed.nodes.values()) {
    for (const s of n.idSpans) eq(s, n.id, `node id ${n.id}`);
    if (n.decl) {
      eq(n.decl.labelSpan, n.decl.label, `decl label ${n.id}`);
      eq(n.decl.openSpan, n.decl.open, `decl open ${n.id}`);
      eq(n.decl.closeSpan, n.decl.close, `decl close ${n.id}`);
      assert.ok(SHAPES[n.decl.shape], `shape table has ${n.decl.shape}`);
      assert.equal(SHAPES[n.decl.shape].open, n.decl.open);
      assert.equal(SHAPES[n.decl.shape].close, n.decl.close);
    }
    for (const c of n.classes) eq(c.span, c.name, `class ${c.name}`);
  }
  for (const e of parsed.edges) {
    eq(e.fromSpan, e.from, `edge from ${e.from}`);
    eq(e.toSpan, e.to, `edge to ${e.to}`);
    if (e.labelSpan) eq(e.labelSpan, e.label, 'edge label');
    assert.equal(e.span[0], e.opSpan[0]);
    assert.ok(e.span[1] >= e.opSpan[1]);
  }
  for (const s of parsed.styles) {
    eq(s.bodySpan, s.body, 'style body');
    for (const t of s.targets) eq(t.span, t.name, 'style target');
  }
  for (const g of parsed.subgraphs) {
    if (g.titleSpan) eq(g.titleSpan, g.title, 'subgraph title');
    if (g.idSpan) eq(g.idSpan, g.id, 'subgraph id');
  }
  if (parsed.header && parsed.header.dirSpan) {
    assert.equal(src.slice(parsed.header.dirSpan[0], parsed.header.dirSpan[1]).toUpperCase(), parsed.header.dir);
  }
}

/** Parses with zero errors and every span round-trips. */
function ok(src) {
  const p = parseFlow(src);
  assert.deepEqual(p.errors, [], `errors for ${JSON.stringify(src)}`);
  checkSpans(p, src, JSON.stringify(src));
  checkRoundTrip(p, src, JSON.stringify(src));
  return p;
}

/** A mutation result must re-parse cleanly. */
const reparsed = (src) => ok(src);

const edgeKeys = (p) => p.edges.map((e) => `${e.from}>${e.to}`);

