describe('shapes', () => {
  const CASES = [
    ['A[text]', 'rect'],
    ['A(text)', 'round'],
    ['A([text])', 'stadium'],
    ['A[[text]]', 'subroutine'],
    ['A[(text)]', 'cylinder'],
    ['A((text))', 'circle'],
    ['A>text]', 'asymmetric'],
    ['A{text}', 'diamond'],
    ['A{{text}}', 'hexagon'],
    ['A[/text/]', 'parallelogram'],
    ['A[\\text\\]', 'parallelogram-alt'],
    ['A[/text\\]', 'trapezoid'],
    ['A[\\text/]', 'trapezoid-alt'],
    ['A(((text)))', 'double-circle']
  ];

  it('SHAPES covers every supported shape exactly once', () => {
    assert.deepEqual(Object.keys(SHAPES).sort(), CASES.map((c) => c[1]).sort());
  });

  for (const [frag, shape] of CASES) {
    it(`${shape}: ${frag}`, () => {
      const src = `graph TD\n${frag}\n`;
      const p = ok(src);
      const d = p.nodes.get('A').decl;
      assert.equal(d.shape, shape);
      assert.equal(d.label, 'text');
      // the brackets around labelSpan really are SHAPES[shape]
      assert.equal(src.slice(d.span[0] + 1, d.labelSpan[0]), SHAPES[shape].open);
      assert.equal(src.slice(d.labelSpan[1], d.span[1]), SHAPES[shape].close);
      // and the same fragment declares when it sits on an edge endpoint
      const q = ok(`graph TD\nZ --> ${frag}\n`);
      assert.equal(q.nodes.get('A').decl.shape, shape);
      assert.equal(q.edges.length, 1);
    });
  }

  it('a quoted label keeps its span inside the quotes, and `;` does not split the statement', () => {
    const src = 'graph TD\nA["a;b (c)"] --> B\n';
    const p = ok(src);
    const d = p.nodes.get('A').decl;
    assert.equal(d.label, 'a;b (c)');
    assert.equal(src[d.labelSpan[0] - 1], '"');
    assert.equal(src[d.labelSpan[1]], '"');
    assert.equal(p.edges.length, 1);
  });
});

