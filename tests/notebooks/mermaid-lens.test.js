describe('dialects', () => {
  const UNIFORM = ['parse', 'shapes', 'nodeIdOf', 'edgeOf', 'name', 'edgeSelector',
                   'setLabel', 'setShape', 'setDirection', 'renameNode',
                   'addEdge', 'setEdgeLabel', 'removeEdge', 'removeNode', 'addNode'];

  it('of() picks the dialect from the header, and null for anything else', () => {
    assert.equal(dialects.of('graph TD\nA-->B\n'), dialects.flow);
    assert.equal(dialects.of('flowchart LR\nA-->B\n'), dialects.flow);
    assert.equal(dialects.of(`${H}A --> B\n`), dialects.state);
    assert.equal(dialects.of('stateDiagram\nA --> B\n'), dialects.state);
    assert.equal(dialects.of('sequenceDiagram\nA->>B: hi\n'), null);
    assert.equal(dialects.of(''), null);
    for (const f of FLOWCHARTS) assert.equal(dialects.of(f.src), dialects.flow, f.name);
    assert.equal(dialects.of(SUBSTRATE.src), dialects.state);
  });

  it('both dialects expose the same method names, wired to the real cells', () => {
    for (const d of [dialects.flow, dialects.state]) {
      for (const k of UNIFORM) assert.ok(k in d, `${d.name} is missing ${k}`);
      assert.ok(Array.isArray(d.shapes) && d.shapes.length > 0, `${d.name} shapes`);
      for (const k of ['parse', 'nodeIdOf', 'edgeOf', 'setLabel', 'setShape', 'setDirection',
                       'renameNode', 'addEdge', 'setEdgeLabel', 'removeEdge', 'removeNode', 'addNode']) {
        assert.equal(typeof d[k], 'function', `${d.name}.${k}`);
      }
    }
    assert.equal(dialects.flow.parse, parseFlow);
    assert.equal(dialects.state.parse, state.parseState);
    assert.equal(dialects.state.setStyle, null, 'stateDiagram has no `style` statement');
    assert.deepEqual(dialects.flow.shapes, Object.keys(SHAPES));
    assert.deepEqual(dialects.state.shapes, state.SHAPES);
  });

  it('the chosen dialect parses and mutates its own source through the uniform interface', () => {
    for (const src of [FLOWCHARTS[0].src, SUBSTRATE.src]) {
      const d = dialects.of(src);
      const p = d.parse(src);
      assert.deepEqual(p.errors, [], d.name);
      const id = [...p.nodes.keys()][0];
      const out = d.setDirection(d.renameNode(src, id, 'Renamed'), 'LR');
      const q = d.parse(out);
      assert.deepEqual(q.errors, [], d.name);
      assert.ok(q.nodes.has('Renamed'), d.name);
      assert.equal(q.header.dir, 'LR', d.name);
      // nodeIdOf reads mermaid's own SVG id convention for this dialect
      assert.equal(d.nodeIdOf({ id: `${d.name === 'flow' ? 'flowchart' : 'state'}-Renamed-1`, classList: new Set() }, q), 'Renamed');
    }
  });
});

