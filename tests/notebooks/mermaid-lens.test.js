describe('edge operators', () => {
  // one entry per link type the parser reports, with that type's spelling variants
  const BY_TYPE = {
    arrow: [['-->', null], ['--x', null], ['---->', null], ['<-->', null], ['-- text -->', 'text']],
    open: [['---', null], ['-------', null], ['-- text ---', 'text']],
    dotted: [['-.->', null], ['-.-', null], ['-. text .->', 'text']],
    thick: [['==>', null], ['===', null], ['== text ==>', 'text']],
    invisible: [['~~~', null]]
  };

  it('EDGE_OPS names every link type the parser reports', () => {
    assert.deepEqual(Object.keys(EDGE_OPS).sort(), Object.keys(BY_TYPE).sort());
  });

  for (const [type, cases] of Object.entries(BY_TYPE)) {
    it(`${type}: ${cases.map((c) => c[0]).join(' ')}`, () => {
      for (const [op, label] of cases) {
        const src = `graph TD\nA ${op} B\n`;
        const p = ok(src);
        assert.equal(p.edges.length, 1, op);
        const e = p.edges[0];
        assert.equal(e.type, type, op);
        assert.equal(e.from, 'A', op);
        assert.equal(e.to, 'B', op);
        assert.equal(e.label, label, op);
        assert.equal(src.slice(e.opSpan[0], e.opSpan[1]), op);
        assert.deepEqual(e.span, e.opSpan, op);
        assert.equal(src.slice(e.statementSpan[0], e.statementSpan[1]), `A ${op} B`);
      }
    });
  }

  it('pipe label: -->|text| widens span past the operator', () => {
    const src = 'graph TD\nA -->|yes| B\n';
    const p = ok(src);
    const e = p.edges[0];
    assert.equal(e.type, 'arrow');
    assert.equal(e.label, 'yes');
    assert.equal(src.slice(e.opSpan[0], e.opSpan[1]), '-->');
    assert.equal(src.slice(e.span[0], e.span[1]), '-->|yes|');
  });
});

