describe('structure', () => {
  it('chain A --> B --> C gives two edges sharing one statement', () => {
    const p = ok('graph TD\nA --> B --> C\n');
    assert.deepEqual(edgeKeys(p), ['A>B', 'B>C']);
    assert.equal(p.edges[0].linkIndex, 0);
    assert.equal(p.edges[1].linkIndex, 1);
    assert.deepEqual(p.edges[0].statementSpan, p.edges[1].statementSpan);
    assert.equal(p.nodes.get('B').idSpans.length, 1);
  });

  it('fan A & B --> C, and a fan on both sides is a cross product', () => {
    assert.deepEqual(edgeKeys(ok('graph TD\nA & B --> C\n')), ['A>C', 'B>C']);
    assert.deepEqual(edgeKeys(ok('graph TD\nA & B --> C & D\n')), ['A>C', 'A>D', 'B>C', 'B>D']);
  });

  it('subgraphs nest, and nodeIds are transitive', () => {
    const src = [
      'flowchart TD',
      '  subgraph outer [Outer box]',
      '    A --> B',
      '    subgraph inner',
      '      C --> D',
      '    end',
      '  end',
      '  B --> C'
    ].join('\n');
    const p = ok(src);
    assert.deepEqual(p.subgraphs.map((g) => g.id), ['outer', 'inner']);
    assert.equal(p.subgraphs[0].title, 'Outer box');
    assert.deepEqual(p.subgraphs[0].nodeIds, ['A', 'B', 'C', 'D']);
    assert.deepEqual(p.subgraphs[1].nodeIds, ['C', 'D']);
    assert.equal(src.slice(p.subgraphs[1].bodySpan[0], p.subgraphs[1].bodySpan[1]).trim(), 'C --> D');
    assert.equal(p.statements.filter((s) => s.kind === 'subgraph').length, 2);
    assert.equal(p.statements.filter((s) => s.kind === 'end').length, 2);
  });

  it('`;`-separated one-liner', () => {
    const src = 'graph TD; A-->B; B-->C';
    const p = ok(src);
    assert.equal(p.header.dir, 'TD');
    assert.deepEqual(edgeKeys(p), ['A>B', 'B>C']);
    assert.deepEqual(p.statements.map((s) => s.kind), ['header', 'edge', 'edge']);
  });

  it('splitStatements ignores separators inside brackets and quotes', () => {
    const src = 'A["a;b\nc"] --> B; C --> D';
    assert.deepEqual(splitStatements(src).map((s) => src.slice(s.span[0], s.span[1])),
      ['A["a;b\nc"] --> B', 'C --> D']);
  });

  it('never throws on junk', () => {
    for (const bad of ['', '   ', 'graph TD\n!!!\n', 'graph TD\nA -->\n', 'graph TD\nA -->|unterminated\n',
                       'graph TD\nend\n', 'graph TD\nsubgraph s\nA-->B\n']) {
      const p = parseFlow(bad);
      assert.ok(Array.isArray(p.errors));
      checkSpans(p, bad, JSON.stringify(bad));
    }
    assert.deepEqual(parseFlow(null).errors, []);
  });
});

